#!/usr/bin/env bash
# Synthetic-scale latency bench for the retrieval surfaces (map, search,
# brief). It builds a deterministic ledger of N documents in a temp dir,
# times each command over three runs, and writes a dated receipt under
# docs/benchmarks/. Run it when a real ledger grows past the doctor
# corpus advisory (DOCTOR013), or when retrieval code changes — receipts
# are the only accepted performance claim, never prose.
#
# Usage: scripts/bench.sh [docs]   (default 1000)
# Requires: go (to build the binary), git (for the receipt's commit sha).
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
DOCS=""
NO_RECEIPT=false
for arg in "$@"; do
	case "$arg" in
	--no-receipt) NO_RECEIPT=true ;;
	*) DOCS="$arg" ;;
	esac
done
DOCS="${DOCS:-1000}"

if [ ! -x pylons/bin/pylon ] || [ cli/cmd/pylon/main.go -nt pylons/bin/pylon ]; then
	echo "building pylons/bin/pylon"
	(cd cli && go build -o ../pylons/bin/pylon ./cmd/pylon)
fi
PYLON="$ROOT/pylons/bin/pylon"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
LEDGER="$STAGE/ledger"
mkdir -p "$LEDGER/manifests" "$LEDGER/references" "$LEDGER/packages" "$LEDGER/plans"
printf 'version: 1\nschemes: []\n' > "$LEDGER/manifests/pylons.yaml"

# Deterministic corpus: rotating 21-word vocabulary so search terms
# hit a stable subset; every doc carries valid frontmatter.
VOCAB=(alpha billing charter delta echo foxtrot gamma harvest indigo juliet kilo lima membership nonce orchard patrol quota roster sierra touchpoint)
for i in $(seq 0 $((DOCS - 1))); do
	name=$(printf "references/bench-%05d.md" "$i")
	{
		printf -- "---\ntitle: Bench %s\ntype: reference\nstatus: active\ncreated: 2026-01-01\nupdated: 2026-01-01\nowners: [Bench]\ntags: []\n---\n\n# Bench %s\n\n" "$i" "$i"
		for j in $(seq 0 39); do
			printf '%s ' "${VOCAB[$(( (i + j) % ${#VOCAB[@]} ))]}"
		done
		printf '\n'
	} > "$LEDGER/$name"
done

# timed CMD: prints one run's wall-clock in ms on stdout.
timed() {
	local t0 t1
	t0=$(date +%s%N)
	"$PYLON" "$@" --pylons "$LEDGER" >/dev/null 2>&1
	t1=$(date +%s%N)
	echo $(( (t1 - t0) / 1000000 ))
}

bench() { # bench <label> <args...> — prints "<label> <median-ms>"
	local label="$1"
	shift
	local runs=() r
	for _ in 1 2 3; do
		r=$(timed "$@")
		runs+=("$r")
	done
	# median of 3
	local ms
	ms=$(printf '%s\n' "${runs[@]}" | sort -n | sed -n '2p')
	echo "$label $ms"
}

echo "ledger: $DOCS docs"
MAP_MS=$(bench "map --all --json" map --all --json | awk '{print $NF}')
SEARCH_MS=$(bench "search membership billing" search membership billing | awk '{print $NF}')
BRIEF_MS=$(bench "brief" brief | awk '{print $NF}')
echo "map:    $MAP_MS ms (median of 3)"
echo "search: $SEARCH_MS ms (median of 3)"
echo "brief:  $BRIEF_MS ms (median of 3)"

if [ "$NO_RECEIPT" = true ]; then
	exit 0
fi

mkdir -p docs/benchmarks
RECEIPT="docs/benchmarks/$(date +%Y-%m-%d)-scale-${DOCS}.md"
SHA="$(git rev-parse --short HEAD)"
VERSION="$("$PYLON" --version 2>/dev/null | awk '{print $2}')"
cat > "$RECEIPT" <<EOF
---
title: Bench receipt ${DOCS}-doc synthetic ledger
type: meta
created: $(date +%Y-%m-%d)
updated: $(date +%Y-%m-%d)
---

# Bench receipt: ${DOCS}-doc synthetic ledger

Measured $(date +%Y-%m-%d) on $(uname -sm), $(nproc) threads, pylon ${VERSION} at commit ${SHA} (pylons/bin/pylon rebuilt if stale). Synthetic corpus: ${DOCS} reference docs, ~40 vocabulary words each, generated by scripts/bench.sh. Median of 3 runs, wall-clock.

| Command | Median |
| --- | --- |
| map --all --json | ${MAP_MS} ms |
| search membership billing | ${SEARCH_MS} ms |
| brief | ${BRIEF_MS} ms |

Run the same script before comparing numbers; receipts without a rerun are history, not a baseline.
EOF
echo "receipt: $RECEIPT"
