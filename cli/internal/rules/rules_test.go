func mustWrite(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestLintCorpusRules(t *testing.T) {
	kb := t.TempDir()
	proj := t.TempDir()

	mustWrite(t, filepath.Join(proj, "cmd/app.go"), "package main\nfunc Run() {}\n")
	mustWrite(t, filepath.Join(kb, "manifests/pylons.yaml"), "version: 1\nextensions: [go]\nprojects:\n  app:\n    path: "+proj+"\n    ref: main\n")

	// Valid plan
	mustWrite(t, filepath.Join(kb, "plans/feat-ok.md"), `---
title: "Valid plan"
type: plan
status: accepted
created: 2026-11-19
updated: 2026-11-19
owners: [estebanforge]
components: [app]
contract:
  stable:
    - kind: go-symbol
      id: repo://app/cmd/app.go::Run
  editing:
    - cmd/**
---

# Valid plan

This plan updates the CLI entry point.
`)

	// Broken: unknown status + broken link + long STE-100 sentence + machine path
	mustWrite(t, filepath.Join(kb, "plans/bad.md"), `---
title: "Bad plan"
type: plan
status: bogus
---

# Bad plan

See [missing](missing.md) and /home/user/secret/file.go for a very long descriptive sentence that intentionally exceeds twenty five words so that the controlled language scanner triggers an error on this exact line without any ambiguity.
`)

	// Shipped plan without artifact in archive/
	mustWrite(t, filepath.Join(kb, "plans/archive/shipped-no-art.md"), `---
title: "Shipped"
type: plan
status: shipped
---

# Shipped

Done.
`)

	// Unnumbered accepted decision
	mustWrite(t, filepath.Join(kb, "decisions/unnumbered.md"), `---
title: "Decision"
type: decision
status: accepted
---

# Decision

Accepted decision.
`)

	findings := Lint(kb, LintOptions{HasCode: true})
	byRule := map[string]bool{}
	for _, f := range findings {
		byRule[f.RuleID] = true
	}

	for _, want := range []string{"PYLON006", "PYLON008", "PYLON009", "PYLON010", "PYLON012", "PYLON033"} {
		if !byRule[want] {
			t.Errorf("expected rule %s to fire; got findings: %+v", want, findings)
		}
	}
	if byRule["PYLON003"] {
		t.Errorf("did not expect PYLON003 on valid go-symbol; findings: %+v", findings)
	}
}

func TestCheckCollisionsAndProtectedGlobs(t *testing.T) {
	kb := t.TempDir()
	mustWrite(t, filepath.Join(kb, "plans/active-work.md"), `---
title: "Active work"
type: plan
status: in-progress
components: [app]
contract:
  editing:
    - cmd/**
  unstable:
    - internal/api/**
---

# Active work

In progress.
`)
	mustWrite(t, filepath.Join(kb, "packages/app.md"), `---
title: "App"
type: package
status: active
package: app
protected:
  - glob: manifests/**
    owner: generated
    reason: "Generated by CI"
  - glob: config/*.yaml
    owner: ask-first
    reason: "Shared config"
---

# App

Core app.
`)

	findings := Check(kb, []string{"cmd/main.go", "manifests/rules.json", "config/app.yaml"})
	if len(findings) != 3 {
		t.Fatalf("expected 3 check findings, got %d: %+v", len(findings), findings)
	}
	// cmd/main.go (editing) -> FORCED, manifests/rules.json (generated) -> FORCED, config/app.yaml (ask-first) -> ADVISORY
	forced := 0
	advisory := 0
	for _, f := range findings {
		if f.Severity == "error" {
			forced++
		} else {
			advisory++
		}
	}
	if forced != 2 || advisory != 1 {
		t.Fatalf("expected 2 forced and 1 advisory, got forced=%d advisory=%d", forced, advisory)
	}
}

// The component filter must accept the package's components, not only its
// name: a package doc titled differently from the project alias still
// protects the alias's paths.
func TestProtectedGlobFiresThroughComponents(t *testing.T) {
	kb := t.TempDir()
	mustWrite(t, filepath.Join(kb, "manifests/pylons.yaml"),
		"version: 1\nextensions: [go]\nprojects:\n  svc:\n    path: svc\n")
	mustWrite(t, filepath.Join(kb, "svc/src/api.go"), "package svc\n")
	mustWrite(t, filepath.Join(kb, "packages/core.md"), `---
title: "Core"
type: package
status: active
package: core
components: [svc]
protected:
  - glob: src/**
    owner: human-only
    reason: "vault keys"
---

# Core
`)
	target := filepath.Join(kb, "svc", "src", "api.go")
	findings := Check(kb, []string{target})
	var found *report.Finding
	for i := range findings {
		if findings[i].RuleID == "PYLON029" {
			found = &findings[i]
		}
	}
	if found == nil {
		t.Fatalf("protected glob must fire through components, got %+v", findings)
	}
}

// A package doc with no components: list covers every alias; the alias
// filter exists only when the doc declares which aliases it speaks for.
func TestProtectedGlobNoComponentsCoversAliases(t *testing.T) {
	kb := t.TempDir()
	mustWrite(t, filepath.Join(kb, "manifests/pylons.yaml"),
		"version: 1\nextensions: [go]\nprojects:\n  svc:\n    path: svc\n")
	mustWrite(t, filepath.Join(kb, "svc/src/api.go"), "package svc\n")
	mustWrite(t, filepath.Join(kb, "packages/core.md"), `---
title: "Core"
type: package
status: active
package: core
protected:
  - glob: "**"
    owner: human-only
    reason: "vault keys"
---

# Core
`)
	findings := Check(kb, []string{filepath.Join(kb, "svc", "src", "api.go")})
	found := false
	for i := range findings {
		if findings[i].RuleID == "PYLON029" {
			found = true
		}
	}
	if !found {
		t.Fatalf("a components-less package must still protect its globs, got %+v", findings)
	}
}

// Declared components exclude foreign aliases: a package speaking for
// svc must not guard other's paths.
func TestProtectedGlobComponentsExcludeForeignAlias(t *testing.T) {
	kb := t.TempDir()
	mustWrite(t, filepath.Join(kb, "manifests/pylons.yaml"),
		"version: 1\nextensions: [go]\nprojects:\n  svc:\n    path: svc\n  other:\n    path: other\n")
	mustWrite(t, filepath.Join(kb, "other/api.go"), "package other\n")
	mustWrite(t, filepath.Join(kb, "packages/core.md"), `---
title: "Core"
type: package
status: active
package: core
components: [svc]
protected:
  - glob: "**"
    owner: human-only
    reason: "vault keys"
---

# Core
`)
	findings := Check(kb, []string{filepath.Join(kb, "other", "api.go")})
	for i := range findings {
		if findings[i].RuleID == "PYLON029" {
			t.Fatalf("a foreign alias must not fire a components-scoped glob: %+v", findings[i])
		}
	}
}
